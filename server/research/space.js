// The pre-registered search space of campaign 1 (strategy/research-runner/CAMPAIGN-1.md section 5), generated
// deterministically from the pinned range-trend configs. Stage 0: the eight planned configs re-run under the
// runner (the baseline among them). Stage 1: single-component changes from the baseline, one field each. Stage 2:
// single-component changes from the other three no-limit bases. Stage 3: selected combinations, built by a rule
// fixed here before any result was read (combinationStage). Every generated config keeps the period, costs,
// starting cash, dividends and benchmark of the base, so runs stay comparable, and every change touches exactly
// one field of levels, exits or portfolio (or the re-entry limit).
