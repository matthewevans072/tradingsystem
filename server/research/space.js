export const COMBINATION_RULE = Object.freeze({ topPerBase: 3, maxPerBase: 4 });

const clone = (v) => JSON.parse(JSON.stringify(v));
export function applyChange(config, field, value) {
  const c = clone(config);
  const [group, key] = field.split('.');
  if (key == null) c[group] = value; else { c[group] = { ...c[group] }; c[group][key] = value; }
  return c;
}
export function getField(config, field) { const [g, k] = field.split('.'); return k == null ? config[g] : config[g]?.[k]; }
const fmt = (v) => (v === null ? 'none' : String(v));
const nameOf = (baseKey, changes) => `${baseKey}+${changes.map(([f, v]) => `${f.split('.')[1] ?? f}=${fmt(v)}`).join('+')}`;

function withVersion(config, name) {
  const c = clone(config);
  c.version = `rr1-${name}`;
  c.label = `Campaign 1 experiment ${name} (exploratory; generated by the research runner)`;
  c.status = 'research-runner experiment (CAMPAIGN-1.md); experimental settings, not the owner\'s trading';
  return c;
}

// The planned experiments of stages 0 to 2, in order. Each carries its config, hash, parent (the base), the
// change and a one-line hypothesis.
export function plannedExperiments() {
  const bases = Object.fromEntries(Object.entries(BASE_FILES).map(([k, f]) => [k, loadConfig(f)]));
  const items = [];
  // Stage 0: the eight planned configs, unchanged (the hashes equal the practice runs' config hashes).
  for (const f of PLANNED_CONFIGS) {
    const config = loadConfig(f);
    items.push({ stage: STAGES.reference, name: f.replace(/\.json$/, ''), baseFile: f, parentKey: null, change: null, config, configHash: experimentHash(config),
      hypothesis: f === BASELINE_FILE ? 'The campaign baseline: the planned trend-immediate-nolimit config, re-run under the runner to fix the comparison figure.' : 'A planned config re-run under the runner for comparison (seen in the practice runs of 2026-11-04).' });
  }
  const single = (baseKey, stage, changes) => {
    const base = bases[baseKey];
    for (const [field, values, meaning] of changes) {
      for (const v of values) {
        if (getField(base, field) === v) continue; // the base's own value: not a change
        const name = nameOf(baseKey, [[field, v]]);
        const config = withVersion(applyChange(base, field, v), name);
        items.push({ stage, name, baseFile: BASE_FILES[baseKey], parentKey: baseKey, change: [{ field, from: getField(base, field), to: v, meaning }], config, configHash: experimentHash(config),
          hypothesis: `${meaning}: ${field} ${fmt(getField(base, field))} -> ${fmt(v)}, everything else as the ${baseKey} base.` });
      }
    }
  };
  single('B', STAGES.singleB, STAGE1_CHANGES);
  for (const k of ['D', 'R', 'P']) single(k, STAGES.singleOthers, STAGE2_CHANGES[k]);
  // Unique by hash (two bases could in principle produce the same config); the development period asserted.
  const seen = new Set(), out = [];
  for (const it of items) { if (seen.has(it.configHash)) continue; seen.add(it.configHash); assertDevelopmentPeriod(it.config); out.push(it); }
  return out;
}

// Stage 3, built after stages 0 to 2 from their stored results by the rule fixed in advance: for each base, the
// single-component changes whose net profit exceeds the base's own net profit and whose maximum drawdown is
// within the limit, ranked by net profit (ties: shallower drawdown, then name); the top 3 are combined pairwise
// and all together (at most 4 configs per base, 16 in all). A base with fewer than two such changes gives no
// combination. Everything is cut at the campaign's configuration budget.
export function combinationStage(experiments, { budgetLeft = LIMITS.maxConfigs, maxDrawdownPct = CRITERIA.maxDrawdownPct } = {}) {
  const bases = Object.fromEntries(Object.entries(BASE_FILES).map(([k, f]) => [k, loadConfig(f)]));
  const done = experiments.filter((e) => e.status === 'done' && e.summary && Number.isFinite(e.summary.net));
  const baseNet = {};
  for (const [k, f] of Object.entries(BASE_FILES)) { const b = done.find((e) => e.stage === STAGES.reference && e.base_file === f); baseNet[k] = b ? b.summary.net : null; }
  const items = [];
  for (const k of Object.keys(BASE_FILES)) {
    if (baseNet[k] == null) continue;
    const singles = done.filter((e) => (e.stage === STAGES.singleB || e.stage === STAGES.singleOthers) && e.base_file === BASE_FILES[k] && Array.isArray(e.change) && e.change.length === 1)
      .filter((e) => e.summary.net > baseNet[k] && e.summary.maxDrawdownPct <= maxDrawdownPct)
      .sort((a, b) => (b.summary.net - a.summary.net) || (a.summary.maxDrawdownPct - b.summary.maxDrawdownPct) || a.name.localeCompare(b.name))
      .slice(0, COMBINATION_RULE.topPerBase);
    if (singles.length < 2) continue;
    const combos = [];
    for (let i = 0; i < singles.length; i++) for (let j2 = i + 1; j2 < singles.length; j2++) combos.push([singles[i], singles[j2]]);
    if (singles.length === 3) combos.push(singles);
    for (const set of combos.slice(0, COMBINATION_RULE.maxPerBase)) {
      const fields = set.map((e) => e.change[0].field);
      if (new Set(fields).size !== fields.length) continue; // two values of one field cannot combine
      let config = bases[k];
      for (const e of set) config = applyChange(config, e.change[0].field, e.change[0].to);
      const name = nameOf(k, set.map((e) => [e.change[0].field, e.change[0].to]));
      config = withVersion(config, name);
      items.push({ stage: STAGES.combinations, name, baseFile: BASE_FILES[k], parentKey: k, parentId: set[0].id, change: set.map((e) => e.change[0]), config, configHash: experimentHash(config),
        hypothesis: `Combination of the top single-component improvements of the ${k} base (${set.map((e) => e.name).join(', ')}), by the pre-registered rule; parents ${set.map((e) => e.id).join(', ')}.` });
    }
  }
  const seen = new Set(), out = [];
  for (const it of items) { if (seen.has(it.configHash)) continue; seen.add(it.configHash); assertDevelopmentPeriod(it.config); out.push(it); }
  return out.slice(0, Math.max(0, budgetLeft));
}

